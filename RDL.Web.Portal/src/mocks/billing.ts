// Documentos del prototipo (DOCS0) en la forma del listado compuesto del gateway: la factura, su estado en
// Hacienda y su saldo, cada uno con su disponibilidad.
type Hac = 'processing' | 'accepted' | 'rejected' | 'contingency' | 'error' | 'unavailable' | null
const d = (
  id: string,
  number: string | undefined,
  documentType: InvoiceListItem['invoice']['documentType'],
  customerId: string,
  issuedOn: string,
  dueDate: string | undefined,
  total: string,
  currency: 'CRC' | 'USD',
  status: InvoiceListItem['invoice']['status'],
  hac: Hac,
  receivableId: string | null,
  requiresCorrection = false,
): InvoiceListItem => {
  const customer = CUSTOMERS.find((x) => x.id === customerId)
  const rec = receivableId ? RECEIVABLES.find((x) => x.id === receivableId) : undefined
  return {
    invoice: {
      id,
      documentType,
      ...(number ? { number } : {}),
      status,
      requiresCorrection,
      customerId,
      ...(status !== 'draft' && customer ? { customerLegalName: customer.legalName } : {}),
      ...(status !== 'draft' ? { issuedAt: `${issuedOn}T15:00:00Z` } : {}),
      ...(dueDate ? { dueDate } : {}),
      currency,
      total,
      createdAt: `${issuedOn}T14:00:00Z`,
    },
    fiscal:
      hac === null
        ? { availability: 'absent' }
        : hac === 'unavailable'
          ? { availability: 'unavailable' }
          : { availability: 'available', status: { electronicDocumentId: `ed-${id}`, status: hac } },
    receivable: rec
      ? {
          availability: 'available',
          balance: {
            receivableId: rec.id,
            status: rec.status,
            currency: rec.currency,
            balanceAmount: rec.balanceAmount,
            dueOn: rec.dueOn,
          },
        }
      : { availability: 'absent' },
  }
}

